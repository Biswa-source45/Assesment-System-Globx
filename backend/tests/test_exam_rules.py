import time

import pytest
from fastapi.testclient import TestClient


@pytest.fixture(scope="module")
def client():
    from app.main import app
    from app.seed import seed
    PW.update({e: p for e, p, _ in seed(reset=True)["staff"]})
    with TestClient(app) as c:
        yield c


PW = {}  # staff passwords, generated by the seed
EXAM = "GLOBX Full-Stack Screening (Sample)"


def _login(c, who, pw):
    r = c.post("/api/v1/auth/login", json={"email": who, "password": pw})
    assert r.status_code == 200, r.text
    return {"Authorization": "Bearer " + r.json()["access_token"]}


def _new_candidate(c, name):
    """Recruiter creates a participant on the sample exam; returns (staff_headers, candidate_headers, assignment_id)."""
    staff = _login(c, "recruiter@globx.co.in", PW["recruiter@globx.co.in"])
    tid = next(t["id"] for t in c.get("/api/v1/tests", headers=staff).json() if t["title"] == EXAM)
    p = c.post(f"/api/v1/tests/{tid}/participants", headers=staff, json={"names": [name]}).json()["participants"][0]
    assert len(p["password"]) == 8 and p["username"].startswith(name.split()[0].lower())
    cand = _login(c, p["username"], p["password"])  # candidate signs in with the generated username
    return staff, cand, p["assignment_id"]


def _start(c, cand, aid):
    r = c.post(f"/api/v1/assignments/{aid}/start", headers=cand, json={"consent": {"accepted": True}, "system_check": {}})
    assert r.status_code == 200, r.text
    return r.json()["attempt_id"]


def _event(c, cand, at, **ev):
    return c.post(f"/api/v1/attempts/{at}/proctor/events", headers=cand, json={"events": [ev]}).json()


def _assignment_status(c, cand, aid):
    return next(a["status"] for a in c.get("/api/v1/me/assignments", headers=cand).json() if a["assignment_id"] == aid)


def test_participant_login_and_password_reset(client):
    staff, cand, aid = _new_candidate(client, "Asha Verma")
    mine = client.get("/api/v1/me/assignments", headers=cand).json()
    assert [a["test"]["title"] for a in mine] == [EXAM] and mine[0]["can_start"]
    new = client.post(f"/api/v1/assignments/{aid}/password", headers=staff).json()
    assert client.post("/api/v1/auth/login", json={"email": new["username"], "password": new["password"]}).status_code == 200
    assert client.post("/api/v1/auth/login", json={"email": new["username"], "password": "wrong-pass1"}).status_code == 401
    assert client.get("/api/v1/tests", headers=cand).status_code == 403  # candidates cannot use staff endpoints


def test_fourth_tab_leave_terminates(client):
    staff, cand, aid = _new_candidate(client, "Bala Rao")
    at = _start(client, cand, aid)
    for i in (1, 2, 3):
        out = _event(client, cand, at, type="tab_blur", duration_ms=2000)
        assert out["action"] == "warn" and out["violations"] == i
    out = _event(client, cand, at, type="tab_blur", duration_ms=2000)
    assert out["action"] == "force_submit"
    assert client.get(f"/api/v1/attempts/{at}", headers=cand).json()["attempt"]["status"] != "in_progress"
    assert _assignment_status(client, cand, aid) != "banned"  # tab violations end the exam but do not ban


def test_fifth_face_incident_bans_until_admin_reset(client):
    staff, cand, aid = _new_candidate(client, "Chitra Das")
    at = _start(client, cand, aid)
    _event(client, cand, at, type="face_missing", duration_ms=1000)  # too short to count
    for i in range(1, 5):
        out = _event(client, cand, at, type="face_missing", duration_ms=4000)
        assert out["action"] == "warn" and out["face_incidents"] == i
    out = _event(client, cand, at, type="multi_face")
    assert out["action"] == "ban"
    for _ in range(60):  # wait for background grading, which must not undo the ban
        if client.get(f"/api/v1/attempts/{at}", headers=cand).json()["attempt"]["status"] in ("review_pending", "evaluated"):
            break
        time.sleep(0.5)
    assert _assignment_status(client, cand, aid) == "banned"
    assert client.post(f"/api/v1/assignments/{aid}/start", headers=cand,
                       json={"consent": {"accepted": True}, "system_check": {}}).status_code == 409
    r = client.post(f"/api/v1/assignments/{aid}/action", headers=staff, json={"action": "reset", "reason": "camera fault"})
    assert r.status_code == 200
    assert _start(client, cand, aid)  # admin reset lets the candidate back in


